"""Summarize results/*__run*.csv into results/summary.md. Generated, never hand-edited.

Runs are grouped by (deployment label, client network); only runs on the same
network are comparable, so each group is reported on its own.

Usage (from the repository root):
    uv run --project backend --group ml python experiments/latency/analyze.py
"""

from __future__ import annotations

from pathlib import Path

import matplotlib

matplotlib.use("Agg")  # files only; no display needed
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
from matplotlib.ticker import FuncFormatter  # noqa: E402

RESULTS = Path(__file__).with_name("results")


def plot(data: pd.DataFrame) -> None:
    """Cumulative distribution of round trips, one line per deployment and
    network: the median and the tail are both readable off it."""
    figure, axis = plt.subplots(figsize=(8, 4.5))
    for (label, network), group in data.groupby(["label", "network"]):
        rtt = np.sort(group["rtt_ms"].to_numpy())
        share = np.arange(1, len(rtt) + 1) / len(rtt)
        axis.plot(rtt, share, label=f"{label} ({network}), n={len(rtt)}")
    axis.set_xscale("log")
    # Plain milliseconds on the ticks rather than 2x10^0 notation.
    plain = FuncFormatter(lambda value, _: f"{value:g}")
    axis.xaxis.set_major_formatter(plain)
    axis.xaxis.set_minor_formatter(plain)
    axis.tick_params(axis="x", which="both", labelsize=8)
    axis.set_xlabel("round trip per frame (ms, log scale)")
    axis.set_ylabel("share of frames")
    axis.set_title("WebSocket round trip, browser frame -> verdict")
    axis.grid(True, which="both", alpha=0.3)
    axis.legend(fontsize=8)
    figure.tight_layout()
    figure.savefig(RESULTS / "latency.png", dpi=150)
    plt.close(figure)


def main() -> None:
    files = sorted(RESULTS.glob("*__run*.csv"))
    if not files:
        raise SystemExit("no runs yet; see run.py")

    frames = []
    for path in files:
        deployment, client_network, stamp, _ = path.stem.split("__")
        one_run = pd.read_csv(path)
        one_run["label"], one_run["network"], one_run["session"] = (
            deployment,
            client_network,
            stamp,
        )
        frames.append(one_run)
    data = pd.concat(frames, ignore_index=True)

    lines = [
        "# Latency results",
        "",
        "Generated by `experiments/latency/analyze.py` from `results/*.csv`. Round trip "
        "is measured on the client's monotonic clock via the echoed `t_client`; "
        "`server_ms` is the API's own evaluation time (features, inference, hints); "
        "*outside* is the rest -- network, TLS, nginx and the API's I/O.",
        "",
        "Compare rows only within the same client network.",
        "",
        "| deployment | client network | frames | RTT p50 | RTT p95 | RTT p99 "
        "| server p50 | server p95 | outside p50 | outside p95 |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for (label, network), group in data.groupby(["label", "network"]):
        rtt, server, outside = group["rtt_ms"], group["server_ms"], group["outside_server_ms"]
        lines.append(
            f"| {label} | {network} | {len(group)} "
            f"| {rtt.median():.1f} | {rtt.quantile(0.95):.1f} | {rtt.quantile(0.99):.1f} "
            f"| {server.median():.2f} | {server.quantile(0.95):.2f} "
            f"| {outside.median():.1f} | {outside.quantile(0.95):.1f} |"
        )

    lines += [
        "",
        "All times in milliseconds.",
        "",
        "## Per run",
        "",
        "Run-to-run agreement shows whether a single minute is representative.",
        "",
        "| deployment | client network | session | run | frames | RTT p50 | RTT p95 |",
        "|---|---|---|---|---|---|---|",
    ]
    for (label, network, session, run), group in data.groupby(
        ["label", "network", "session", "run"]
    ):
        lines.append(
            f"| {label} | {network} | {session} | {run} | {len(group)} "
            f"| {group['rtt_ms'].median():.1f} | {group['rtt_ms'].quantile(0.95):.1f} |"
        )

    plot(data)
    marker = "Compare rows only within the same client network."
    lines.insert(lines.index(marker), "![round trip](latency.png)\n")
    (RESULTS / "summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
