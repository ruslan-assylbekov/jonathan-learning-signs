"""Summarize results/*__rep*.csv into results/summary.md. Generated, never hand-edited.

Runs are grouped by (deployment label, client network). For every repeat the
capacity is the largest step that passed before the first failing one.

Usage (from the repository root):
    uv run --project backend --group ml python experiments/loadtest/analyze.py
"""

from __future__ import annotations

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")  # files only; no display needed
import matplotlib.pyplot as plt  # noqa: E402
import pandas as pd  # noqa: E402
from matplotlib.ticker import FuncFormatter  # noqa: E402

RESULTS = Path(__file__).with_name("results")


def load() -> pd.DataFrame:
    frames = []
    for path in sorted(RESULTS.glob("*__rep*.csv")):
        deployment, client_network, stamp, _ = path.stem.split("__")
        one = pd.read_csv(path)
        one["label"], one["network"], one["session"] = deployment, client_network, stamp
        one["api_cpu_percent"] = api_cpu(path.stem.rsplit("__", 1)[0], one)
        frames.append(one)
    if not frames:
        raise SystemExit("no runs yet; see run.py")
    return pd.concat(frames, ignore_index=True)


def api_cpu(prefix: str, steps: pd.DataFrame) -> list[float]:
    """Mean `docker stats` CPU of the API container inside each step's window
    (100 % = one core), when the run sampled server stats."""
    stats_file = RESULTS / f"{prefix}__server_stats.csv"
    if not stats_file.is_file() or stats_file.stat().st_size < 10:
        return [float("nan")] * len(steps)
    stats = pd.read_csv(stats_file)
    api = stats[stats["container"].str.contains("api")]
    values = []
    for step in steps.itertuples(index=False):
        within = api["unix"].between(step.window_start_unix, step.window_end_unix)
        inside = api[within]
        values.append(float(inside["cpu_percent"].mean()) if len(inside) else float("nan"))
    return values


def capacity(run: pd.DataFrame) -> tuple[int | None, str]:
    """Largest passing step before the first failure, and why the ramp ended."""
    run = run.sort_values("users")
    passed = None
    for users, verdict in zip(run["users"].tolist(), run["verdict"].tolist(), strict=True):
        if verdict != "ok":
            return passed, f"{verdict} at {users}"
        passed = int(users)
    return passed, "never failed (raise --steps)"


def plot(data: pd.DataFrame, max_p95_ms: float | None) -> None:
    figure, (latency, throughput) = plt.subplots(1, 2, figsize=(11, 4.5))
    for (label, network), group in data.groupby(["label", "network"]):
        for i, (_, run) in enumerate(group.groupby(["session", "repeat"])):
            run = run.sort_values("users")
            name = f"{label} ({network})" if i == 0 else None
            color = latency.plot(run["users"], run["rtt_p95_ms"], "o-", alpha=0.7, label=name)[
                0
            ].get_color()
            throughput.plot(run["users"], run["achieved_hz"], "o-", color=color, alpha=0.7)
    if max_p95_ms is not None:
        latency.axhline(
            max_p95_ms, color="grey", linestyle="--", linewidth=1, label="p95 threshold"
        )
    top = int(data["users"].max())
    throughput.plot(
        [0, top], [0, top * 15], color="grey", linestyle="--", linewidth=1, label="offered"
    )
    throughput.legend(fontsize=8)
    latency.set_yscale("log")
    plain = FuncFormatter(lambda value, _: f"{value:g}")
    latency.yaxis.set_major_formatter(plain)
    # Label 2, 3 and 5 between decades; all nine minor ticks crowd the axis.
    latency.yaxis.set_minor_formatter(
        FuncFormatter(lambda value, _: f"{value:g}" if f"{value:g}"[0] in "235" else "")
    )
    latency.tick_params(axis="y", which="both", labelsize=8)
    latency.set_xlabel("concurrent users")
    latency.set_ylabel("round trip p95 (ms, log scale)")
    latency.set_title("Latency under load (one line per repeat)")
    latency.legend(fontsize=8)
    throughput.set_xlabel("concurrent users")
    throughput.set_ylabel("frames answered per second")
    throughput.set_title("Throughput")
    for axis in (latency, throughput):
        axis.grid(True, which="both", alpha=0.3)
    figure.tight_layout()
    figure.savefig(RESULTS / "loadtest.png", dpi=150)
    plt.close(figure)


def main() -> None:
    data = load()
    environments = {
        path.stem.rsplit("__", 1)[0]: json.loads(path.read_text(encoding="utf-8"))
        for path in RESULTS.glob("*__environment.json")
    }
    thresholds = {env["max_p95_ms"] for env in environments.values()}

    lines = [
        "# Load test results",
        "",
        "Generated by `experiments/loadtest/analyze.py` from `results/*.csv`. "
        "Each user streams real frames at 15 Hz; a step is measured after a warm-up. "
        "Capacity = the largest step that passed before the first failing step. "
        "Times in milliseconds; *API CPU* is `docker stats` for the API container "
        "(100 % = one core), when sampled.",
        "",
        "![load test](loadtest.png)",
        "",
        "## Capacity per repeat",
        "",
        "| deployment | client network | session | repeat | capacity (users) | ramp ended by |",
        "|---|---|---|---|---|---|",
    ]
    for (label, network, session, repeat), run in data.groupby(
        ["label", "network", "session", "repeat"]
    ):
        held, reason = capacity(run)
        lines.append(
            f"| {label} | {network} | {session} | {repeat} "
            f"| {held if held is not None else 'none'} | {reason} |"
        )

    lines += [
        "",
        "## Per step (median over repeats that reached it)",
        "",
        "| deployment | client network | users | repeats | answered/s | offered/s "
        "| RTT p50 | RTT p95 | RTT p99 | server p95 | loss | API CPU | verdicts |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for (label, network, users), step in data.groupby(["label", "network", "users"]):
        verdicts = ", ".join(f"{v} x{n}" for v, n in step["verdict"].value_counts().items())
        cpu = step["api_cpu_percent"].median()
        lines.append(
            f"| {label} | {network} | {users} | {len(step)} "
            f"| {step['achieved_hz'].median():.1f} | {step['offered_hz'].median():.0f} "
            f"| {step['rtt_p50_ms'].median():.1f} | {step['rtt_p95_ms'].median():.1f} "
            f"| {step['rtt_p99_ms'].median():.1f} | {step['server_p95_ms'].median():.2f} "
            f"| {step['loss'].median():.2%} | {'' if pd.isna(cpu) else f'{cpu:.0f} %'} "
            f"| {verdicts} |"
        )

    lines += ["", "## Environment", ""]
    for prefix, env in sorted(environments.items()):
        lines += [f"`{prefix}`", "", "```json", json.dumps(env, indent=2), "```", ""]

    plot(data, thresholds.pop() if len(thresholds) == 1 else None)
    (RESULTS / "summary.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines[:40]))


if __name__ == "__main__":
    main()
