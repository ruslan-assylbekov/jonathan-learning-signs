"""Summarize results/*.csv into results/summary.md. Generated, never hand-edited.

Usage (from the repository root):
    uv run --project backend --group ml python experiments/bandwidth/analyze.py
"""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

RESULTS = Path(__file__).with_name("results")
SEND_HZ = 15
"""ws-client.ts throttles frames to 15 Hz (CLAUDE.md 7)."""
CAMERA_FPS = 30
"""What streaming every camera frame would mean instead."""


def ws_frame_bytes(payload: float, *, masked: bool) -> float:
    header = 2 + (0 if payload < 126 else 2 if payload < 65536 else 8)
    return payload + header + (4 if masked else 0)


def kb(value: float) -> str:
    return f"{value / 1000:,.2f}"


def mb(value: float) -> str:
    return f"{value / 1_000_000:,.2f}"


def main() -> None:
    marks = pd.read_csv(RESULTS / "landmarks.csv")
    jpeg = pd.read_csv(RESULTS / "jpeg.csv")
    env = json.loads((RESULTS / "environment.json").read_text(encoding="utf-8"))

    frame_wire = marks["frame_wire"].mean()
    reply_wire = marks["reply_wire"].mean()
    up_per_min = frame_wire * SEND_HZ * 60
    down_per_min = reply_wire * SEND_HZ * 60

    lines = [
        "# Bandwidth results",
        "",
        "Generated by `experiments/bandwidth/analyze.py` from `results/*.csv`.",
        f"{len(marks)} landmark messages and {len(jpeg)} JPEG encodings over seeds "
        f"{sorted(marks['seed'].unique().tolist())}. 1 kB = 1,000 bytes, 1 MB = 10^6 bytes.",
        "Wire sizes include WebSocket framing (RFC 6455); TLS record overhead is not included.",
        "",
        "## Per message",
        "",
        "| message | median | mean | p95 | max |",
        "|---|---|---|---|---|",
    ]
    for label, column in [
        ("frame, payload (what ws-client.ts sends)", "frame_payload"),
        ("frame, on the wire", "frame_wire"),
        ("frame, payload if rounded to 4 decimals *(not sent today)*", "frame_payload_rounded4"),
        ("eval reply, payload", "reply_payload"),
        ("eval reply, on the wire", "reply_wire"),
    ]:
        series = marks[column]
        lines.append(
            f"| {label} | {series.median():.0f} B | {series.mean():.0f} B "
            f"| {series.quantile(0.95):.0f} B | {series.max():.0f} B |"
        )
    lines += [
        "",
        f"Replies carrying at least one hint: {(marks['reply_hints'] > 0).mean():.1%} "
        "(learner attempting the letter being shown).",
        "",
        f"## Landmarks per session, at the client's {SEND_HZ} Hz",
        "",
        "| direction | per second | per minute |",
        "|---|---|---|",
        f"| up (frames) | {kb(frame_wire * SEND_HZ)} kB | {kb(up_per_min)} kB |",
        f"| down (eval replies) | {kb(reply_wire * SEND_HZ)} kB | {kb(down_per_min)} kB |",
        f"| both | {kb((frame_wire + reply_wire) * SEND_HZ)} kB "
        f"| {kb(up_per_min + down_per_min)} kB |",
        "",
        "## JPEG frames instead (upload only)",
        "",
        f"Mean JPEG size per frame, and per minute uploaded at {SEND_HZ} Hz (the same "
        f"rate as landmarks) and at {CAMERA_FPS} fps (every camera frame). "
        "`x landmarks` compares against landmark upload at the same 15 Hz.",
        "",
        "| frame size | quality | mean frame | p95 frame "
        f"| per min @ {SEND_HZ} Hz | per min @ {CAMERA_FPS} fps | x landmarks |",
        "|---|---|---|---|---|---|---|",
    ]

    for (long_side, quality), group in jpeg.groupby(["long_side", "quality"]):
        mean_wire = ws_frame_bytes(group["jpeg_bytes"].mean(), masked=True)
        per_min = mean_wire * SEND_HZ * 60
        size = f"{group['width'].mode().iloc[0]}x{group['height'].mode().iloc[0]}"
        lines.append(
            f"| long side {long_side} (typ. {size}) | {quality} "
            f"| {kb(float(group['jpeg_bytes'].mean()))} kB "
            f"| {kb(float(group['jpeg_bytes'].quantile(0.95)))} kB "
            f"| {mb(per_min)} MB | {mb(mean_wire * CAMERA_FPS * 60)} MB "
            f"| {per_min / up_per_min:,.0f}x |"
        )

    precision_file = RESULTS / "precision.csv"
    if precision_file.is_file():
        precision = pd.read_csv(precision_file)
        lines += [
            "",
            "## Rounding before sending: accuracy cost (`precision.py`)",
            "",
            "model-v2 on the held-out test signers with landmarks rounded before feature "
            "extraction. Frames whose rounding collapses two joints are rejected "
            "(INVALID_FRAME) and count as misses.",
            "",
            "| decimals | accuracy | macro F1 | predictions changed | frames made invalid |",
            "|---|---|---|---|---|",
            *[
                f"| {row.decimals} | {row.accuracy:.4f} | {row.macro_f1:.4f} "
                f"| {row.predictions_changed_vs_full} of {row.frames} | {row.frames_made_invalid} |"
                for row in precision.itertuples(index=False)
            ],
        ]

    lines += [
        "",
        "## Stability across samples",
        "",
        "Medians per seed; close agreement means the result does not hinge on which "
        "frames were sampled.",
        "",
        "| seed | frame payload | reply payload | JPEG 1280 q75 |",
        "|---|---|---|---|",
    ]
    reference = jpeg[(jpeg["long_side"] == 1280) & (jpeg["quality"] == 75)]
    for seed in sorted(marks["seed"].unique()):
        lines.append(
            f"| {seed} | {marks[marks.seed == seed]['frame_payload'].median():.0f} B "
            f"| {marks[marks.seed == seed]['reply_payload'].median():.0f} B "
            f"| {kb(float(reference[reference.seed == seed]['jpeg_bytes'].median()))} kB |"
        )

    lines += [
        "",
        "## Environment",
        "",
        "```json",
        json.dumps(env, indent=2),
        "```",
        "",
    ]
    (RESULTS / "summary.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines[:60]))


if __name__ == "__main__":
    main()
